#!/usr/bin/env bash
# Prepare ONE isolated Codex workspace from a trusted A/B snapshot archive.
# No network, API credentials, or source checkout is needed here.
set -euo pipefail
if [[ $# -ne 3 ]]; then
  echo 'Usage: prepare-agent-workspace.sh /path/snapshot.tar.gz a|b /empty/workspace' >&2
  exit 2
fi
archive="$(realpath "$1")"
arm="$2"
case "$arm" in a|b) ;; *) echo 'Arm must be a or b' >&2; exit 2;; esac
dest="$3"
mkdir -p "$dest"
dest="$(cd "$dest" && pwd)"
if find "$dest" -mindepth 1 -maxdepth 1 | grep -q .; then
  echo "Refusing to populate nonempty destination: $dest" >&2
  exit 2
fi
# These tar files are generated by make-snapshots.sh from a frozen trusted Git
# commit. strip-components removes the single wrapping arm-* directory.
tar -xzf "$archive" -C "$dest" --strip-components=1
[[ -f "$dest/TASK.md" && -f "$dest/labs/reservation-lab/package.json" ]] || {
  echo 'Snapshot is missing the shared task or application' >&2; exit 1;
}
if [[ "$arm" == a ]]; then
  [[ ! -e "$dest/AGENTS.md" && ! -e "$dest/technical-library" && ! -e "$dest/.agents" ]] || {
    echo 'Reference data leaked into control arm A' >&2; exit 1;
  }
else
  [[ -f "$dest/AGENTS.md" && -f "$dest/technical-library/INDEX.md" ]] || {
    echo 'Reference data missing from Louvre arm B' >&2; exit 1;
  }
fi
[[ ! -e "$dest/experiments/codex-ab-01/evaluator" ]] || {
  echo 'Independent evaluator leaked into coding workspace' >&2; exit 1;
}
# Codex CLI requires a Git repo. This local history is isolated from Louvre and
# is never pushed; its initial commit is the common baseline for patch capture.
git -C "$dest" init -q
git -C "$dest" config user.name 'Louvre benchmark baseline'
git -C "$dest" config user.email 'louvre-benchmark@users.noreply.github.com'
git -C "$dest" add -A
git -C "$dest" commit -qm 'Frozen baseline for isolated Codex arm'
echo "Prepared isolated Codex arm $arm in $dest"