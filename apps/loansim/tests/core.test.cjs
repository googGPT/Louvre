const t=require('node:test'),a=require('node:assert/strict'),C=require('../core.js');const v={principal:1200,apr:0,months:12,extra:0,fees:0};
t('zéro taux mensualité en centimes',()=>a.equal(C.payment(v),10000));
t('taux zéro aucun intérêt',()=>a.equal(C.schedule(v).interestSum,0));
t('12 mensualités à taux zéro',()=>a.equal(C.schedule(v).rows.length,12));
t('solde final zéro',()=>a.equal(C.schedule(v).rows.at(-1).balance,0));
t('paiement anticipé réduit durée',()=>a.ok(C.compare({...v,extra:100}).monthsSaved>0));
t('paiement anticipé réduit intérêts',()=>a.ok(C.compare({...v,apr:10,extra:100}).interestSaved>0));
t('frais exclus mensualité',()=>a.equal(C.payment({...v,fees:200}),C.payment(v)));
t('frais ajoutés au coût global',()=>a.equal(C.schedule({...v,fees:100}).totalCost,10000));
t('taux positif mensualité positive',()=>a.ok(C.payment({...v,apr:3})>10000));
t('paramètres rejet montant négatif',()=>a.throws(()=>C.validate({...v,principal:-1})));
t('refuse durée non entière',()=>a.throws(()=>C.validate({...v,months:4.5})));
t('refuse taux infini',()=>a.throws(()=>C.validate({...v,apr:Infinity})));
t('refuse supplément négatif',()=>a.throws(()=>C.validate({...v,extra:-1})));
t('refuse champ inconnu',()=>a.throws(()=>C.validate({...v,secret:1})));
t('échéancier CSV contient en-tête et 12 mois',()=>a.equal(C.csv(C.schedule(v)).trim().split('\n').length,13));
t('sans supplément économies zéro',()=>a.equal(C.compare(v).interestSaved,0));
t('versement anticipé ne dépasse pas dette résiduelle',()=>a.ok(C.schedule({...v,extra:10000}).rows[0].payment<=120000));
t('échéance finale ajuste les centimes et solde nul à taux élevé',()=>a.equal(C.schedule({...v,principal:280000,apr:7.35,months:360}).rows.at(-1).balance,0));
