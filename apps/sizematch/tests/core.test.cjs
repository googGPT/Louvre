const test=require('node:test'),assert=require('node:assert/strict'),L=require('../core.js');
const base={id:'sample0001',name:'Balade',value:12,from:'km',to:'mile'};
const r=(x={})=>({...base,...x});
const CSV_FR={headers:['Nom','Valeur initiale','Unité initiale','Valeur convertie','Unité cible','Catégorie']};
const near=(actual,expected,tolerance=1e-9)=>assert.ok(Math.abs(actual-expected)<=tolerance,`${actual} ≠ ${expected}`);
test('identifiant et quatre champs de la v1 conservés',()=>{assert.equal(L.SPEC.slug,'sizematch');assert.equal(L.SPEC.fields.length,4)});
test('conservation sans mutation des anciennes fiches',()=>{assert.deepEqual(L.normalizeRecord(base),base)});
test('ancienne sauvegarde JSON v1 importable',()=>{const a=L.validateBackup({app:'sizematch',version:1,records:[base]});assert.deepEqual(a,[base])});
test('export JSON v1 restaurable',()=>{const raw=L.backup([base]);assert.equal(JSON.parse(raw).version,1);assert.deepEqual(L.validateBackup(JSON.parse(raw)),[base])});
test('sauvegarde appli différente rejetée',()=>assert.throws(()=>L.validateBackup({app:'other',version:1,records:[base]})));
test('sauvegarde future rejetée',()=>assert.throws(()=>L.validateBackup({app:'sizematch',version:2,records:[base]})));
test('objet sauvegarde manquant rejeté',()=>assert.throws(()=>L.validateBackup(null)));
test('sauvegarde JSON v1 refuse les champs top-level supplémentaires mais conserve exportedAt',()=>{
  const saved=JSON.parse(L.backup([base]));
  assert.deepEqual(L.validateBackup(saved),[base]);
  assert.throws(()=>L.validateBackup({...saved,unexpected:true}),/err\.backup/);
  assert.throws(()=>L.validateBackup({...saved,exportedAt:12345}),/err\.backup/);
});
test('un enregistrement restauré ne doit pas contenir de propriété supplémentaire',()=>{
  assert.throws(()=>L.validateBackup({app:'sizematch',version:1,records:[{...base,unknown:1}]}),/err\.backup/);
});
test('doublons id rejetés',()=>assert.throws(()=>L.validateBackup({app:'sizematch',version:1,records:[base,base]})));
test('limite 500 enregistrements',()=>assert.throws(()=>L.validateBackup({app:'sizematch',version:1,records:Array.from({length:501},(_,i)=>r({id:'id'+String(i).padStart(5,'0')}))})));
test('identifiant malformé rejeté',()=>assert.throws(()=>L.normalizeRecord(r({id:'a'}))));
test('tableaux rejetés en entrée',()=>assert.throws(()=>L.normalizeRecord([])));
test('nom vide refusé',()=>assert.throws(()=>L.normalizeRecord(r({name:'  '}))));
test('nom trop long refusé',()=>assert.throws(()=>L.normalizeRecord(r({name:'X'.repeat(161)}))));
test('valeur manquante refusée',()=>assert.throws(()=>L.normalizeRecord(r({value:undefined}))));
test('nombre sous forme de chaîne refusé',()=>assert.throws(()=>L.normalizeRecord(r({value:'12'}))));
test('NaN interdit',()=>assert.throws(()=>L.convert(NaN,'km','mile')));
test('Infini interdit',()=>assert.throws(()=>L.convert(Infinity,'km','mile')));
test('valeur excessive refusée',()=>assert.throws(()=>L.convert(100000001,'km','mile')));
test('unités inconnues refusées',()=>assert.throws(()=>L.convert(1,'other','km')));
test('unités incompatibles refusées',()=>assert.throws(()=>L.convert(1,'kg','m')));
test('même catégorie nécessaire à la sauvegarde',()=>assert.throws(()=>L.normalizeRecord(r({to:'kg'}))));
test('distance négative refusée',()=>assert.throws(()=>L.convert(-1,'km','mile')));
test('masse négative refusée',()=>assert.throws(()=>L.convert(-1,'kg','lb')));
test('volume négatif refusé',()=>assert.throws(()=>L.convert(-1,'L','gal US')));
test('température négative Celsius acceptée',()=>near(L.convert(-10,'°C','°F'),14));
test('température négative Fahrenheit acceptée',()=>near(L.convert(-4,'°F','°C'),-20));
test('zéro Celsius en Fahrenheit',()=>near(L.convert(0,'°C','°F'),32));
test('100 °C en °F',()=>near(L.convert(100,'°C','°F'),212));
test('Kelvin à Celsius',()=>near(L.convert(273.15,'K','°C'),0));
test('Kelvin à Fahrenheit',()=>near(L.convert(0,'K','°F'),-459.67));
test('−273.15 °C égale zéro Kelvin',()=>near(L.convert(-273.15,'°C','K'),0));
test('température sous zéro absolu Celsius refusée',()=>assert.throws(()=>L.convert(-274,'°C','°F')));
test('température sous zéro absolu Fahrenheit refusée',()=>assert.throws(()=>L.convert(-460,'°F','K')));
test('Kelvin négatif refusé',()=>assert.throws(()=>L.convert(-1,'K','°C')));
test('miles : facteur international exact',()=>near(L.convert(1,'mile','km'),1.609344));
test('12 km restent environ 7.456 miles',()=>near(L.convert(12,'km','mile'),7.456454306848,1e-9));
test('pieds : 12 pouces dans 1 ft',()=>near(L.convert(12,'in','ft'),1));
test('1 yard = 3 ft',()=>near(L.convert(1,'yd','ft'),3));
test('100 cm = 1 m',()=>near(L.convert(100,'cm','m'),1));
test('1000 mm = 1 m',()=>near(L.convert(1000,'mm','m'),1));
test('une livre = 0.45359237 kg',()=>near(L.convert(1,'lb','kg'),0.45359237));
test('16 oz = 1 lb',()=>near(L.convert(16,'oz','lb'),1));
test('1000 g = 1 kg',()=>near(L.convert(1000,'g','kg'),1));
test('1 gallon US = 3.785411784 L',()=>near(L.convert(1,'gal US','L'),3.785411784));
test('128 fl oz US = 1 gal US',()=>near(L.convert(128,'fl oz US','gal US'),1));
test('1000 mL = 1 L',()=>near(L.convert(1000,'mL','L'),1));
test('aller-retour pour chaque groupe',()=>{for(const group of Object.values(L.GROUPS)){for(const from of group){for(const to of group){let v=L.category(from)==='température'?10:17.35;const back=L.convert(L.convert(v,from,to),to,from);near(back,v,1e-8);}}}});
test('comptage des catégories réellement utilisées',()=>{const a=L.compute([base,r({id:'sample0002',from:'°C',to:'°F',value:-10}),r({id:'sample0003',from:'kg',to:'lb',value:5})]);assert.equal(a.kpis[2][1],'3')});
test('calcule correctement à vide',()=>{const a=L.compute([]);assert.equal(a.kpis[0][1],'0');assert.equal(a.rows.length,0)});
test('valide la date du calcul',()=>assert.throws(()=>L.compute([],'2026-02-30')));
test('changement d’heure local ne déforme pas le nombre de jours',()=>{assert.equal(L.diffDays('2026-03-30','2026-03-29'),1);assert.equal(L.addDays('2026-03-28',2),'2026-03-30')});
test('une très petite valeur ne s’affiche pas comme zéro',()=>{assert.notEqual(L.formatValue(0.0000000001),'0');assert.match(L.formatValue(0.0000000001),/e-/)});
test('précision lisible sur conversion usuelle',()=>assert.match(L.formatValue(L.convert(12,'km','mile')),/^7,456/));
test('zéro affiché simplement',()=>assert.equal(L.formatValue(0),'0'));
test('valeur d’affichage invalide refusée',()=>assert.throws(()=>L.formatValue(Infinity)));
test('petite température positive conservée en Kelvin',()=>assert.equal(L.convert(1e-13,'K','K'),1e-13));
test('petite température signée conservée en Celsius',()=>assert.equal(L.convert(-1e-13,'°C','°C'),-1e-13));
test('Kelvin légèrement négatif interdit sans tolérance arbitraire',()=>assert.throws(()=>L.convert(-1e-13,'K','K'),/err\.absoluteZero/));
test('Celsius juste sous zéro absolu interdit',()=>assert.throws(()=>L.convert(-273.15000000000003,'°C','K'),/err\.absoluteZero/));
test('Fahrenheit juste sous zéro absolu interdit',()=>assert.throws(()=>L.convert(-459.6700000000001,'°F','K'),/err\.absoluteZero/));
test('CSV ne transforme pas une petite température positive en zéro',()=>{
  const csv=L.toCSV([r({name:'Cryogénie',value:1e-13,from:'K',to:'K'})],CSV_FR);
  assert.match(csv,/"Cryogénie";1e-13;"K";1e-13;"K"/);
});
test('CSV exportable, Unicode et BOM',()=>{const csv=L.toCSV([base],CSV_FR);assert.ok(csv.startsWith('\uFEFF'));assert.ok(csv.includes('Balade'));assert.ok(csv.includes('Valeur convertie'))});
test('CSV protège les formules',()=>{const csv=L.toCSV([r({name:'=IMPORTXML("x")'})],CSV_FR);assert.match(csv,/"'=IMPORTXML/)});
test('CSV sépare et échappe les guillemets',()=>assert.match(L.toCSV([r({name:'un "nom"; étrange'})],CSV_FR),/"un ""nom""; étrange"/));
test('les anciennes fiches ne sont pas modifiées par compute',()=>{const raw=JSON.stringify(base);L.compute([base]);assert.equal(JSON.stringify(base),raw)});
test('aucune dépendance réseau ou variable navigateur dans le cœur',()=>assert.equal(typeof L.convert,'function'));
test('CSV garde les températures négatives en cellules numériques',()=>{
  const csv=L.toCSV([r({name:'Froid',from:'°C',to:'°F',value:-20})],CSV_FR);
  assert.match(csv,/"Froid";-20;"°C";-4;"°F"/);
  assert.doesNotMatch(csv,/;"'-20"/);
});
test('CSV fournit la virgule décimale pour Excel français',()=>{
  const csv=L.toCSV([r({name:'Essai',from:'km',to:'m',value:1.5})],CSV_FR);
  assert.match(csv,/"Essai";1,5;"km";1500;"m"/);
});
test('CSV continue à neutraliser les noms qui commencent par moins',()=>{
  const csv=L.toCSV([r({name:'-HYPERLINK("https://example.com")'})],CSV_FR);
  assert.match(csv,/"'-HYPERLINK/);
});
test('notation exponentielle produit neuf chiffres significatifs',()=>{
  assert.equal(L.formatValue(0.000000000123456789),'1.23456789e-10');
});
